#!/usr/bin/env bash
#
# 一键构建三种 Linux 安装包
#
#   ./packaging/build.sh          # 构建全部（能构建多少算多少）
#   ./packaging/build.sh deb      # 只构建 .deb
#   ./packaging/build.sh arch     # 只构建 .pkg.tar.zst
#   ./packaging/build.sh rpm      # 只构建 .rpm
#
# 产物输出到 dist/
#
# 依赖：
#   .deb        → dpkg-deb（Debian/Ubuntu 自带，Arch 可装 dpkg）
#   .pkg.tar.zst→ makepkg 或 libarchive（Arch 自带）
#   .rpm        → rpmbuild（dnf install rpm-build / pacman -S rpm-tools）

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

PKG_NAME="coolapk-desktop"
PKG_VERSION="${VERSION:-1.0.0}"
PKG_ARCH="amd64"
DIST="$ROOT/dist"
STAGE="$ROOT/build/pkgroot"

# 目标（可选参数）
TARGET="${1:-all}"

say()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }

have() { command -v "$1" >/dev/null 2>&1; }

# ---------------------------------------------------------------- 构建二进制
build_binary() {
    if [ ! -x "$ROOT/build/$PKG_NAME" ]; then
        say "编译二进制…"
        make -C "$ROOT" || die "编译失败"
    else
        say "复用已有二进制（make clean 可强制重建）"
    fi
    [ -x "$ROOT/build/$PKG_NAME" ] || die "找不到 $ROOT/build/$PKG_NAME"
}

# ---------------------------------------------------------------- 组装目录树
# 所有包共用同一套文件布局：
#   usr/bin/<bin>                        可执行文件
#   usr/share/applications/*.desktop     桌面入口
#   usr/share/icons/hicolor/<N>x<N>/apps 图标
#   usr/share/doc/<pkg>/                 文档
#   usr/share/licenses/<pkg>/            许可证
stage_files() {
    say "组装安装树 → $STAGE"
    rm -rf "$STAGE"
    mkdir -p "$STAGE/usr/bin"
    mkdir -p "$STAGE/usr/share/applications"
    mkdir -p "$STAGE/usr/share/doc/$PKG_NAME"
    mkdir -p "$STAGE/usr/share/licenses/$PKG_NAME"

    install -m755 "$ROOT/build/$PKG_NAME" "$STAGE/usr/bin/$PKG_NAME"
    install -m644 "$ROOT/packaging/common/$PKG_NAME.desktop" \
        "$STAGE/usr/share/applications/$PKG_NAME.desktop"

    for s in 32 48 64 128 256; do
        src="$ROOT/assets/$PKG_NAME-$s.png"
        [ -f "$src" ] || continue
        mkdir -p "$STAGE/usr/share/icons/hicolor/${s}x${s}/apps"
        install -m644 "$src" "$STAGE/usr/share/icons/hicolor/${s}x${s}/apps/$PKG_NAME.png"
    done

    [ -f "$ROOT/README.md" ] && install -m644 "$ROOT/README.md" \
        "$STAGE/usr/share/doc/$PKG_NAME/README.md"
    [ -f "$ROOT/docs/PLUGINS.md" ] && install -m644 "$ROOT/docs/PLUGINS.md" \
        "$STAGE/usr/share/doc/$PKG_NAME/PLUGINS.md"
    [ -f "$ROOT/LICENSE" ] && install -m644 "$ROOT/LICENSE" \
        "$STAGE/usr/share/licenses/$PKG_NAME/LICENSE"
}

# ---------------------------------------------------------------- .deb
build_deb() {
    say "构建 .deb"
    have dpkg-deb || { warn "缺少 dpkg-deb，跳过 .deb"; return 0; }

    local work="$ROOT/build/deb"
    rm -rf "$work"
    mkdir -p "$work/DEBIAN"
    cp -a "$STAGE/." "$work/"

    # 控制文件里的版本/架构按实际填
    sed -e "s/^Version:.*/Version: $PKG_VERSION/" \
        -e "s/^Architecture:.*/Architecture: $PKG_ARCH/" \
        "$ROOT/packaging/deb/DEBIAN/control" > "$work/DEBIAN/control"

    # 装完刷新桌面数据库与图标缓存
    cat > "$work/DEBIAN/postinst" <<'EOS'
#!/bin/sh
set -e
if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database -q /usr/share/applications || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -q -t -f /usr/share/icons/hicolor || true
fi
exit 0
EOS
    chmod 755 "$work/DEBIAN/postinst"
    cp "$work/DEBIAN/postinst" "$work/DEBIAN/postrm"

    mkdir -p "$DIST"
    local out="$DIST/${PKG_NAME}_${PKG_VERSION}_${PKG_ARCH}.deb"
    dpkg-deb --build --root-owner-group "$work" "$out" >/dev/null
    say "生成 $out  ($(du -h "$out" | cut -f1))"
}

# ---------------------------------------------------------------- Arch
build_arch() {
    say "构建 Arch 包（.pkg.tar.zst）"
    local work="$ROOT/build/arch"
    rm -rf "$work"
    mkdir -p "$work"
    cp -a "$STAGE/." "$work/"

    # .PKGINFO
    {
        echo "# Generated by packaging/build.sh"
        echo "pkgname = $PKG_NAME"
        echo "pkgbase = $PKG_NAME"
        echo "pkgver = ${PKG_VERSION}-1"
        echo "pkgdesc = 桌面版酷安（第三方酷安客户端）"
        echo "url = https://github.com/desktopcoolapk/desktopcoolapk"
        echo "builddate = $(date +%s)"
        echo "packager = DesktopCoolAPK Contributors"
        echo "size = $(du -sb "$work" | cut -f1)"
        echo "arch = x86_64"
        echo "license = GPL3"
        echo "depend = webkit2gtk-4.1"
        echo "depend = gtk3"
        echo "depend = curl"
        echo "depend = openssl"
        echo "optdepend = android-tools: ADB 安装 APK"
    } > "$work/.PKGINFO"

    # .INSTALL 脚本
    cat > "$work/.INSTALL" <<'EOS'
post_install() {
    update-desktop-database -q 2>/dev/null || true
    gtk-update-icon-cache -q -t -f /usr/share/icons/hicolor 2>/dev/null || true
}
post_upgrade() { post_install; }
post_remove()  { post_install; }
EOS

    # 文件清单
    ( cd "$work" && find . -type f ! -name '.PKGINFO' ! -name '.INSTALL' ! -name '.MTREE' \
        | sed 's|^\./||' | sort ) > "$work/.FILELIST"

    mkdir -p "$DIST"
    local base="$DIST/${PKG_NAME}-${PKG_VERSION}-1-x86_64.pkg.tar"

    # 打包：元数据文件 + 完整 usr/ 树
    local zst=""
    have zstd && zst="yes"
    if [ -n "$zst" ]; then
        ( cd "$work" && tar -cf - .PKGINFO .INSTALL .FILELIST usr ) | zstd -q -T0 -o "${base}.zst"
        out="${base}.zst"
    else
        ( cd "$work" && tar -czf "${base}.gz" .PKGINFO .INSTALL .FILELIST usr )
        out="${base}.gz"
    fi
    say "生成 $out  ($(du -h "$out" | cut -f1))"
}

# ---------------------------------------------------------------- RPM
build_rpm() {
    say "构建 .rpm"
    if ! have rpmbuild; then
        warn "缺少 rpmbuild，跳过 .rpm"
        warn "  安装：Fedora  dnf install rpm-build"
        warn "        Arch    sudo pacman -S rpm-tools"
        warn "  spec 文件已备好：packaging/rpm/coolapk-desktop.spec"
        return 0
    fi

    local top="$ROOT/build/rpmbuild"
    rm -rf "$top"
    mkdir -p "$top"/{BUILD,RPMS,SOURCES,SPECS,SRPMS}

    # 源码包：必须带顶层目录，spec 里 %setup 会 cd 进去
    local srcname="${PKG_NAME}-${PKG_VERSION}"
    mkdir -p "$top/SOURCES/build/$srcname"
    cp -a "$STAGE/." "$top/SOURCES/build/$srcname/"
    ( cd "$top/SOURCES/build" && tar -czf "../../SOURCES/${srcname}.tar.gz" "$srcname" )
    rm -rf "$top/SOURCES/build"

    sed -e "s/^Version:.*/Version:        $PKG_VERSION/" \
        "$ROOT/packaging/rpm/coolapk-desktop.spec" > "$top/SPECS/$PKG_NAME.spec"

    # Arch 等非 RPM 系发行版没有 /var/lib/rpm，用独立数据库
    mkdir -p "$top/db"
    rpmbuild --define "_topdir $top" --define "_dbpath $top/db" \
        --define "debug_package %{nil}" -bb \
        "$top/SPECS/$PKG_NAME.spec" 2>&1 | grep -E "^错误|^error|Wrote:|%|line" | tail -8
    mkdir -p "$DIST"
    find "$top/RPMS" -name '*.rpm' -exec cp {} "$DIST/" \;
    say "生成 RPM："
    ls -la "$DIST"/*.rpm 2>/dev/null | awk '{print "   " $NF "  (" $5 " bytes)"}'
}

# ---------------------------------------------------------------- 主流程
build_binary
stage_files

case "$TARGET" in
    all)  build_deb; build_arch; build_rpm ;;
    deb)  build_deb ;;
    arch) build_arch ;;
    rpm)  build_rpm ;;
    *)    die "未知目标：$TARGET（可用：all / deb / arch / rpm）" ;;
esac

say "完成。产物目录：$DIST"
ls -la "$DIST" 2>/dev/null || true
